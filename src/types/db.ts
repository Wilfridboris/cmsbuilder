/**
 * Database row + logical-schema types for the shared-JSONB tenant model
 * (Story 1.2). Shared by the guarded write layer (`mutate.ts`), the read
 * layer (`records.ts`), the seed script, and the RLS isolation test.
 *
 * There is NO per-tenant physical table: a "table" is logical — a `table_key`
 * plus a `TableDefinition` in the org's `org_schemas.definition`.
 */

/** A single field within a logical table definition. */
export type FieldDefinition = {
  /** Normalized snake_case key used inside `records.data`. */
  key: string;
  /** Human-facing column label (rename edits this, not `key`). */
  label: string;
  /**
   * Rendering/validation hint. Story 1.4 widened the union to the full
   * generation contract: the base scalar set plus `datetime`, `email`, `phone`.
   * Story 1.8 adds `relation` — a single-reference link to another table's
   * record (see `relationConfig`). A `relation` cell stores the target record's
   * UUID in `records.data`, never the label; the label resolves at read time
   * from the target table's `displayField`.
   */
  type:
    | "text"
    | "number"
    | "date"
    | "datetime"
    | "boolean"
    | "currency"
    | "email"
    | "phone"
    | "relation";
  /**
   * Present only when `type === "relation"` (Story 1.8). Describes the link:
   * `targetTable` is the `TableDefinition.key` this field points at, and
   * `cardinality` is `"one"` at MVP (a single reference). `"many"` (multi-select)
   * is Growth-only and rejected by the validator on the generation path.
   */
  relationConfig?: {
    targetTable: string;
    cardinality: "one" | "many";
  };
  /** Plain-language reason this field exists (FR46 explainability). */
  reason?: string;
  /** Append-only hide flag — a display concern, never a data delete. */
  hidden?: boolean;
  /** Marks PII for PIPEDA handling (FR40). */
  sensitive?: boolean;
};

/** A logical table: a normalized key + its ordered field definitions. */
export type TableDefinition = {
  /** Normalized snake_case logical-table key (matches `records.table_key`). */
  key: string;
  /** Human-facing table label. */
  label: string;
  /** Plain-language reason this table exists (FR46 explainability). */
  reason?: string;
  /**
   * Append-only hide flag — a display concern, never a data delete. Mirrors
   * `FieldDefinition.hidden`: a removed table drops out of `visibleTables`
   * (and the tablist) while its definition and any `records` stay intact.
   * Backward-compatible optional JSONB field — no migration.
   */
  hidden?: boolean;
  /**
   * The canonical label field for this table (Story 1.8, FR75): the non-hidden
   * field key whose value represents a row wherever it appears as a relation
   * reference. Provisioning defaults it (first non-hidden `text` field, else the
   * first non-hidden field) when generation omits it. Optional JSONB field,
   * backward-compatible — no migration.
   */
  displayField?: string;
  /** Ordered field definitions rendered as columns. */
  fields: FieldDefinition[];
};

/** The full authoritative logical schema stored in `org_schemas.definition`. */
export type SchemaDefinition = {
  tables: TableDefinition[];
  /**
   * True when this schema was provisioned from the hardcoded universal fallback
   * template (Story 1.5), not generated by the LLM. Persisted into
   * `org_schemas.definition` (no migration) so it survives read-back and claim,
   * and mirrored into the generate response so `/generate` can show the subtle
   * "starter template" banner. Successful generations omit it (falsy).
   */
  isFallback?: boolean;
};

