/**
 * Typed platform invoice parent row (Story 12.2) — NOT the JSONB records store.
 * Mirrors every column of `20260928120200_invoices.sql` (money columns from 12.3;
 * issue columns from 12.4). Drafting starts at `status='draft'`; 12.4 flips it to
 * `'issued'` and freezes `invoice_number` / `issue_date` / the snapshots /
 * `share_token`. `pdf_path` is added by 12.5. `customer_record_id` is a LOOSE
 * reference to `records.id` (ON DELETE SET NULL); the customer label resolves at read
 * time for a draft and from `customer_snapshot` after issue.
 */
export type InvoiceRow = {
  id: string;
  organization_id: string;
  customer_record_id: string | null;
  place_of_supply_province: string | null;
  language: InvoiceLanguage;
  status: InvoiceStatus;
  version: number;
  actor_id: string | null;
  /**
   * Money totals (Story 12.3). Written ONLY from `computeInvoiceTotals` output on
   * every draft save (Invariant I2): `subtotal = Σ line amounts`, `tax_total =
   * Σ tax lines` (0 when no tax applies), `total = subtotal + tax_total`. Existing
   * 12.2 drafts read as 0 until their next save. PostgREST returns numeric columns
   * as strings, so they are typed `number | string` at the row boundary.
   */
  subtotal: number | string;
  tax_total: number | string;
  total: number | string;
  /**
   * Issue-time frozen columns (Story 12.4). All null until issued. `invoice_number`
   * is the gap-free per-org integer (I1; PostgREST returns bigint as a string);
   * `issue_date` is the server-authoritative `YYYY-MM-DD`; the snapshots freeze
   * supplier/customer identity (I6); `share_token` is the one-time 128-bit token (I4).
   */
  invoice_number: number | string | null;
  issue_date: string | null;
  supplier_snapshot: SupplierSnapshot | null;
  customer_snapshot: CustomerSnapshot | null;
  share_token: string | null;
  /**
   * Optional owner-set due date (Story 12.7, `YYYY-MM-DD`). Set on the draft via
   * `save_invoice_draft` and frozen at issue by the immutability trigger (not in the
   * mutable whitelist). Drives the read-time Overdue label on the Invoices receivables
   * view (an issued invoice whose `due_date` is before today), which is derived only —
   * `overdue` is never written to `status`. Null means Unpaid but never Overdue.
   */
  due_date: string | null;
  /**
   * The bucket-relative object key of the frozen invoice PDF in the private
   * `invoice-pdfs` bucket (Story 12.5, I5): `{organization_id}/{invoice_id}.pdf`.
   * Null until the post-issue `ensureInvoicePdf` freeze succeeds; the immutability
   * trigger permits exactly one `null->value` write of this column on a non-draft
   * invoice, so a failed freeze stays retryable.
   */
  pdf_path: string | null;
  created_at: string;
  updated_at: string;
};

